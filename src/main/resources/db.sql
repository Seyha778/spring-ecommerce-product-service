
-- ============================================================
-- 2. PRODUCT SERVICE
-- ============================================================

-- Products
CREATE TABLE IF NOT EXISTS ecommerce.products (
                                                  id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    product_code VARCHAR(100) NOT NULL UNIQUE,
    product_name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) UNIQUE,
    description TEXT,
    category_id VARCHAR(150),
    brand_name VARCHAR(150),
    price NUMERIC(18,2) NOT NULL DEFAULT 0,
    compare_at_price NUMERIC(18,2),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    product_status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    created_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by varchar(255) NULL,
    modified_on TIMESTAMPTZ,
    modified_by varchar(255) null,

    CONSTRAINT chk_product_price CHECK (price >= 0),
    CONSTRAINT chk_product_compare_price
    CHECK (compare_at_price IS NULL OR compare_at_price >= 0)
    );

-- Product categories
CREATE TABLE IF NOT EXISTS ecommerce.product_categories (
                                                            id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    category_name VARCHAR(150) NOT NULL,
    category_code VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    parent_category_id VARCHAR(150),
    image_url TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    display_order INTEGER NOT NULL DEFAULT 0,
    created_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by varchar(255) NULL,
    modified_on TIMESTAMPTZ,
    modified_by varchar(255) null
    );

-- Product images
CREATE TABLE IF NOT EXISTS ecommerce.product_images (
                                                        id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    product_id VARCHAR(30) NOT NULL,
    image_url TEXT NOT NULL,
    image_type VARCHAR(30) DEFAULT 'PRODUCT',
    display_order INTEGER NOT NULL DEFAULT 0,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by varchar(255) NULL
    );

-- Product inventory
CREATE TABLE IF NOT EXISTS ecommerce.product_inventory (
                                                           id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    product_id VARCHAR(30) NOT NULL,
    sku VARCHAR(100) NOT NULL UNIQUE,
    quantity_available INTEGER NOT NULL DEFAULT 0,
    quantity_reserved INTEGER NOT NULL DEFAULT 0,
    quantity_sold INTEGER NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER NOT NULL DEFAULT 5,
    modified_on TIMESTAMPTZ,
    modified_by varchar(255) null,

    CONSTRAINT chk_inventory_available CHECK (quantity_available >= 0),
    CONSTRAINT chk_inventory_reserved CHECK (quantity_reserved >= 0),
    CONSTRAINT chk_inventory_sold CHECK (quantity_sold >= 0),
    CONSTRAINT chk_inventory_threshold CHECK (low_stock_threshold >= 0)
    );
